"""Generate synthetic teaching data and calculate reports with GAWorld.

Run from an initialized GAWorld workspace. No model or simulation is called.
Outputs go to a new directory: tutorial-reading-sample.
"""
import csv
import json
from pathlib import Path

from gaworld.parallel.spec import normalize_experiment
from gaworld.parallel.runner import prepare_experiment, analyze_experiment
from gaworld.research.protocol import protocol_from_answer, preflight
from gaworld.research.evaluate import evaluate

out = Path('tutorial-reading-sample')
out.mkdir(exist_ok=False)

def save(name, value):
    (out / name).write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

conditions = [
    {'id': 'baseline', 'label': '基准', 'role': 'baseline', 'events': []},
    {'id': 'subsidy', 'label': '补贴通告', 'role': 'treatment', 'events': [
        {'day': 2, 'time': '09:00', 'name': '租金补贴通告',
         'description': '市政部门宣布为低收入家庭提供租金补贴。'}]},
    {'id': 'placebo', 'label': '例行通告', 'role': 'placebo', 'events': [
        {'day': 2, 'time': '09:00', 'name': '例行通告',
         'description': '市政部门发布办公时间未发生变化的例行通告。'}]},
]
worlds = {'name': '补贴通告与压力：教学配置', 'sim_days': 3, 'seed': 42,
          'agent_ids': list(range(1, 9)), 'fast': False, 'max_parallel': 1,
          'baseline_id': 'baseline', 'worlds': conditions}
save('worlds.json', worlds)
answer = {'title': '补贴通告与压力：教学协议', 'sample': {'agent_ids': list(range(1, 9))},
          'sim_days': 3, 'fast': False, 'max_parallel': 1, 'conditions': conditions,
          'measures': ['stress'], 'hypotheses': [
              {'id': 'H1', 'statement': '补贴通告条件下的期末压力低于基准条件',
               'measure': 'stress', 'treatment': 'subsidy', 'control': 'baseline',
               'direction': 'decrease', 'min_effect': 0.02, 'aggregation': 'final'}],
          'validity': {'seeds': [42, 43], 'placebo': True}}
save('protocol-input.json', answer)
protocol = protocol_from_answer(answer, {'id': 'tutorial', 'language': 'zh-CN'})
check = preflight(protocol, default_agents=8)
assert check['ok'], check['errors']
save('protocol.json', protocol.to_dict())
save('preflight.json', check)
runs = []
for seed in [42, 43]:
    spec = normalize_experiment({**worlds, 'seed': seed})
    manifest = prepare_experiment(spec, str(out), output_root='fixtures', experiment_id=f'seed-{seed}')
    for world_id, entry in manifest['worlds'].items():
        path = out / entry['state_csv']
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open('w', newline='', encoding='utf-8') as stream:
            writer = csv.writer(stream)
            writer.writerow(['agent_id', 'step', 'metric', 'value'])
            for agent_id in range(1, 9):
                for step in range(6):
                    value = 0.4 + agent_id * 0.01 + step * 0.01
                    if step >= 2:
                        value += {'baseline': 0, 'subsidy': (-0.10 if seed == 42 else -0.08) + (agent_id - 4.5) * 0.004,
                                  'placebo': 0.005}[world_id]
                    writer.writerow([agent_id, step, 'stress', round(value, 4)])
        if seed == 42:
            (out / f'{world_id}-state.csv').write_bytes(path.read_bytes())
    manifest['status'] = 'done'
    report = analyze_experiment(str(out), manifest)
    save(f'report-seed-{seed}.json', report)
    runs.append({'seed': seed, 'status': 'done', 'report': report})
save('evaluation.json', evaluate(protocol, runs))
save('SOURCE.json', {'kind': 'synthetic teaching fixture',
                    'inputs': 'CSV values generated by build-reading-sample.py; no LLM calls.',
                    'calculation': 'GAWorld normalize_experiment, preflight, analyze_experiment, evaluate',
                    'purpose': 'Teach file formats and result interpretation; not empirical findings.'})
print('Created', out.resolve())
print('Preflight:', check['ok'], 'estimated calls:', check['budget']['estimated_calls'])
h = evaluate(protocol, runs)['hypotheses'][0]
print('H1:', h['mean_effect'], h['verdict'])
